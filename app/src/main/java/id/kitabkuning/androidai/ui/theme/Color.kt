/** Static scheme for [palette]; DINAMIS falls back to HIJAU off Android 12+. */
internal fun colorSchemeFor(palette: ColorPalette, darkTheme: Boolean): ColorScheme =
    when (palette) {
        ColorPalette.HIJAU, ColorPalette.DINAMIS -> if (darkTheme) HijauDarkScheme else HijauLightScheme
        ColorPalette.SEPIA -> if (darkTheme) SepiaDarkScheme else SepiaLightScheme
        ColorPalette.BIRU -> if (darkTheme) BiruDarkScheme else BiruLightScheme
        ColorPalette.UNGU -> if (darkTheme) UnguDarkScheme else UnguLightScheme
    }
